export type MessageKey = keyof typeof messages.en;

export function detectLanguage(): Language {
  try {
    const saved = localStorage.getItem("rpi-web-language");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    // Storage may be unavailable.
  }
  const languages = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];
  return languages.some((value) => value?.toLowerCase().startsWith("zh"))
    ? "zh"
    : "en";
}

export function saveLanguage(language: Language) {
  try {
    localStorage.setItem("rpi-web-language", language);
  } catch {
    // Storage may be unavailable.
  }
}

export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const text = messages[language][key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(values[name] ?? placeholder),
  );
}

