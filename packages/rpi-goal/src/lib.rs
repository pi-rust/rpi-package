/// Environment markers meaning "this process is a subagent spawned by an
/// orchestrator". Such a process shares the parent's session directory and its
/// parent's goal, so its turns must not be counted or continued separately.
const ORCHESTRATOR_SUBAGENT_ENV: &str = "RPI_ORCHESTRATOR_SUBAGENT";

fn is_subagent_from(orchestrator_marker: bool, langfuse_parent: bool) -> bool {
    orchestrator_marker || langfuse_parent
}

static PROCESS_IS_SUBAGENT: AtomicBool = AtomicBool::new(false);

/// Capture inherited markers once at plugin initialization. Langfuse also
/// publishes its parent trace marker in the parent process during a run, for
/// future children to inherit; reading that marker later misclassifies the
/// parent, so it is sampled here only.
fn capture_process_role() {
    PROCESS_IS_SUBAGENT.store(
        is_subagent_from(
            std::env::var_os(ORCHESTRATOR_SUBAGENT_ENV).is_some(),
            std::env::var_os(rpi_plugin_sdk::SUBAGENT_PARENT_TRACE_ID_ENV).is_some(),
        ),
        Ordering::Relaxed,
    );
}

pub fn is_subagent() -> bool {
    PROCESS_IS_SUBAGENT.load(Ordering::Relaxed)
}

/// Runtime actions the pinned SDK (0.3.20) does not name yet.
///
/// The ABI carries a raw `u32`, so a newer host action is still callable; an
/// older host rejects it with an explicit "unknown runtime action id" error
/// instead of misbehaving, which is what makes the feature detection below safe.
pub mod raw_actions {
    /// `Abort` — cancel the in-flight main-lane run. Present in the host runtime
    /// (id 27) but not in the published SDK that this crate pins.
    pub const ABORT: u32 = 27;
}

/// Call a host runtime action (e.g. `AppendEntry`, `SendMessage`). Safe from any
/// thread, including event handlers and the continuation worker. Never call this
/// while holding a lock the host may re-enter through this plugin.
pub fn call_runtime(id: RuntimeActionId, args: Value) -> Result<Value, String> {
    call_runtime_raw(id as u32, args)
}

/// Numeric form, for actions the pinned SDK does not enumerate.
pub fn call_runtime_raw(id: u32, args: Value) -> Result<Value, String> {
    let runtime = runtime::snapshot().ok_or("goal runtime is unavailable")?;
    let input = args.to_string();
    let mut output = StbString::empty();
    let rc = (runtime.runtime_action)(
        id,
        StbStringRef::from_str(&input),
        &mut output,
        runtime.user_data,
    );
    let text = output.to_string_lossy();
    (runtime.free_string)(output);
    if rc != 0 {
        return Err(if text.is_empty() {
            format!("runtime action {id} failed")
        } else {
            text
        });
    }
    if text.trim().is_empty() {
        Ok(Value::Null)
    } else {
        serde_json::from_str(&text).map_err(|e| format!("invalid runtime response: {e}"))
    }
}

rpi_plugin_sdk::export_plugin!(|api| {
    capture_process_role();
    runtime::install(*api);
    events::register(api);
    if let Some(register_command) = api.register_command {
        let _ = register_command(
            StbStringRef::from_str("goal"),
            StbStringRef::from_str("Show, start, pause, stop, or budget the active goal"),
            command::handler() as CommandHandlerFn,
        );
    } else {
        return 1;
    }
    tools::register(api)
});

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn subagent_detection_accepts_either_marker() {
        assert!(is_subagent_from(true, false));
        assert!(is_subagent_from(false, true));
        assert!(is_subagent_from(true, true));
        assert!(!is_subagent_from(false, false));
    }

    #[test]
    fn subagent_role_defaults_to_false() {
        // No markers are set in the test process.
        assert!(!is_subagent());
    }

    #[test]
    fn runtime_calls_without_a_host_report_unavailability() {
        let error = call_runtime(RuntimeActionId::GetSessionBranch, serde_json::json!({}))
            .expect_err("no host runtime is installed in unit tests");
        assert!(error.contains("unavailable"), "{error}");
    }
}
