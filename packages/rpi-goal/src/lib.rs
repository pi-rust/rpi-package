//! rpi-goal: one session-scoped objective that keeps working.
//!
//! Goal mode is a small state machine on the current session branch plus one
//! continuation worker:
//!
//! * state lives in a `goal-state` custom entry (bounded reads, no project file);
//! * `AgentSettled` wakes the worker, which dispatches at most one automatic run
//!   per settled boundary through the blocking `SendMessage` action;
//! * `goal_complete` / `goal_blocked` / `goal_wait` give every managed run an
//!   explicit stopping reason, guarded by the current goal id;
//! * budgets (turns / time / tokens) and safety limits (automatic turns,
//!   repeated tool-free output) stop work instead of guessing completion.
#![forbid(unsafe_code)]
// The plugin entrypoint is generated by the SDK macro, which dereferences the
// host-owned API pointer behind the ABI contract. The warning is about the
// generated signature, not about plugin code.
#![allow(clippy::not_unsafe_ptr_arg_deref)]

